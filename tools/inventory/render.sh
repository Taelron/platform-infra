#!/usr/bin/env bash
# Builds /platform/inventory/index.html from every root's JSON.
# Usage: render.sh <dir with <root>.json> [<a live Platform page, for its sidebar>]
set -euo pipefail
dir=$1
sidebar_src=${2:-}

# The Platform sidebar of a live page, with this page marked current; a
# minimal one if no page could be read.
sidebar=""
if [ -n "$sidebar_src" ] && [ -s "$sidebar_src" ]; then
  sidebar=$(sed -n '/<nav class="sidebar"/,/<\/nav>/p' "$sidebar_src" | sed 's/ aria-current="page"//g')
fi
if [ -z "$sidebar" ]; then
  sidebar='<nav class="sidebar" aria-label="Platform pages"><p class="nav-label"><a href="/platform/" style="color:inherit">Platform</a></p><ol class="tree"></ol></nav>'
fi
if grep -q 'href="/platform/inventory/"' <<<"$sidebar"; then
  sidebar=$(sed 's|href="/platform/inventory/"|href="/platform/inventory/" aria-current="page"|' <<<"$sidebar")
else
  sidebar=$(sed 's|</ol>|<li><a href="/platform/inventory/" aria-current="page">Inventory</a></li></ol>|' <<<"$sidebar")
fi

body=$(jq -r -s '
  def esc: tostring | @html;
  def cell: if . == null or . == "" then "—" else esc end;
  def detail: [to_entries[] | "\(.key | gsub("_"; " ")): \(.value)"] | join(", ") | cell;
  (map(.resources[]) ) as $res
  | ($res | group_by(.project // "untagged")) as $projects
  | [
      "<h2 id=\"roots\">Roots</h2>",
      "<div class=\"table-box\"><table><thead><tr><th>Root</th><th>Last apply (UTC)</th><th>Commit</th><th>Listed</th><th>Untaggable</th></tr></thead><tbody>",
      (sort_by(.root)[] | "<tr><td><code>tofu/\(.root | esc)</code></td><td>\(.generated_at | sub("T"; " ") | sub("Z$"; "") | esc)</td><td><code>\(.commit[0:7] | esc)</code></td><td>\(.resources | length)</td><td>\(.untaggable)</td></tr>"),
      "</tbody></table></div>",
      "<h2 id=\"projects\">Projects</h2>",
      "<div class=\"table-box\"><table><thead><tr><th>Project</th><th>Resources</th><th>Components</th></tr></thead><tbody>",
      ($projects[] | "<tr><td>\(.[0].project | cell)</td><td>\(length)</td><td>\([.[].component // "untagged"] | unique | join(", ") | esc)</td></tr>"),
      "</tbody></table></div>",
      ($projects[] as $p
       | "<h2 id=\"\($p[0].project // "untagged" | esc)\">\($p[0].project // "untagged" | esc)</h2>",
         ($p | group_by(.component // "untagged")[]
          | "<h3>\(.[0].component // "untagged" | esc)</h3>",
            "<div class=\"table-box\"><table><thead><tr><th>Name</th><th>Type</th><th>Region</th><th>State or size</th></tr></thead><tbody>",
            (.[] | "<tr><td>\(.name | cell)</td><td><code>\(.type | esc)</code></td><td>\(.region | cell)</td><td>\(.details | detail)</td></tr>"),
            "</tbody></table></div>"))
    ] | join("\n")
' "$dir"/*.json)

toc=$(jq -r -s '
  ([map(.resources[]) | group_by(.project // "untagged")[] | .[0].project // "untagged"]) as $p
  | (["roots", "projects"] + $p)
  | map("<li><a href=\"#\(. | @html)\">\(if . == "roots" then "Roots" elif . == "projects" then "Projects" else . end | @html)</a></li>")
  | join("")
' "$dir"/*.json)

updated=$(jq -r -s 'map(.generated_at) | max | sub("T.*"; "")' "$dir"/*.json)

cat <<HTML
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Inventory — Taelron Docs</title>
<link rel="stylesheet" href="/assets/site.css">
</head>
<body>
<header class="topbar">
  <div class="topbar-inner">
    <a class="brand" href="/"><span class="brand-mark">&gt;_</span> Taelron Docs</a>
    <nav class="spaces" aria-label="Spaces">
      <a href="/handbook/">Handbook</a>
      <a href="/platform/" aria-current="page">Platform</a>
      <a href="/fleetdesk/">FleetDesk</a>
    </nav>
    <div class="account">
      <a class="btn" href="/signout">Sign out</a>
    </div>
  </div>
</header>

<div class="doc">
  $sidebar

  <main class="doc-main">
    <nav class="breadcrumb" aria-label="Breadcrumb">
      <a href="/">Home</a><span aria-hidden="true">/</span><a href="/platform/">Platform</a><span aria-hidden="true">/</span><span>Inventory</span>
    </nav>
    <h1>Inventory</h1>
    <p class="lead">What OpenTofu has provisioned in AWS, by project and component. Rebuilt after every apply; resources AWS cannot tag are only counted.</p>

$body

    <div class="page-meta">
      <span>Generated by the OpenTofu pipeline of <code>platform-infra</code></span>
      <span>Updated $updated</span>
    </div>
  </main>

  <nav class="toc" aria-label="On this page">
    <p class="nav-label">On this page</p>
    <ul>$toc</ul>
  </nav>
</div>

<footer class="footer">
  <div class="footer-inner">
    <span>Taelron</span>
    <span class="mono">Source of truth: Linear</span>
  </div>
</footer>
</body>
</html>
HTML
